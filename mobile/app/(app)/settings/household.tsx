import { useCallback, useState } from 'react';
import { AccessibilityInfo, ScrollView, StyleSheet, Text, View } from 'react-native';
import { useRouter, type Href } from 'expo-router';
import { Button } from '@/components/Button';
import { AppBar, IconButton } from '@/components/Chrome';
import { EmptyIcon } from '@/components/EmptyIcon';
import { FormBanner } from '@/components/FormBanner';
import { Row, RowSubtitle, RowTitle } from '@/components/Row';
import { useSnackbar } from '@/components/Snackbar';
import { COPY } from '@/copy/strings';
import { JoinSheet } from '@/household/JoinSheet';
import { NameSheet } from '@/household/NameSheet';
import {
  PendingChangesError,
  householdErrorMessage,
  useHouseholdActions,
  useHouseholds,
} from '@/household/useHousehold';
import { useSpaces } from '@/household/useSpaces';
import { savedHaptic, warnHaptic } from '@/lib/haptics';
import { radius, space, type } from '@/theme/tokens';
import { createStyles } from '@/theme/ThemeProvider';

/**
 * Households (`docs/design/13-multiple-households.md`): every household the person is in, and the ways to
 * start or join another. A row opens that household; the one whose books are open says so.
 *
 * Membership is server state, so this screen needs the network and says so plainly when it has none.
 * Creating and joining move the device into the new household, which clears the rows it holds, so the
 * actions (`useHouseholdActions`) refuse while changes are waiting to sync.
 */
/**
 * A household's page. Cast because typed routes are generated by the dev server from the files under
 * `app/`, and a route added since the last run is not in them yet.
 */
function detailHref(id: string): Href {
  return { pathname: '/(app)/settings/household-detail', params: { id } } as unknown as Href;
}

export default function HouseholdsScreen() {
  const styles = useStyles();
  const router = useRouter();
  const showSnackbar = useSnackbar();
  const households = useHouseholds();
  const actions = useHouseholdActions();
  const { active } = useSpaces();

  const [joinOpen, setJoinOpen] = useState(false);
  const [joinError, setJoinError] = useState<string | undefined>(undefined);
  const [createOpen, setCreateOpen] = useState(false);
  const [createError, setCreateError] = useState<string | undefined>(undefined);

  const done = useCallback(
    (message: string) => {
      savedHaptic();
      showSnackbar({ message });
      AccessibilityInfo.announceForAccessibility(message);
    },
    [showSnackbar],
  );

  const create = useCallback(
    async (name: string) => {
      setCreateError(undefined);
      try {
        await actions.create(name);
        setCreateOpen(false);
        done(COPY.household.snack.created);
      } catch (error) {
        warnHaptic();
        setCreateError(householdErrorMessage(error));
      }
    },
    [actions, done],
  );

  const join = useCallback(
    async (code: string) => {
      setJoinError(undefined);
      try {
        await actions.join(code);
        setJoinOpen(false);
        done(COPY.household.snack.joined);
      } catch (error) {
        warnHaptic();
        setJoinError(
          error instanceof PendingChangesError ? error.message : householdErrorMessage(error),
        );
      }
    },
    [actions, done],
  );

  const list = households.data;

  return (
    <View style={styles.screen}>
      <AppBar
        title={COPY.household.listTitle}
        leading={
          <IconButton
            icon="chevron-left"
            label={COPY.common.back}
            onPress={() => router.back()}
            testID="households-back"
          />
        }
      />

      <ScrollView contentContainerStyle={styles.content}>
        {households.isError ? (
          <View style={styles.centered}>
            <FormBanner
              message={householdErrorMessage(households.error)}
              testID="households-banner"
            />
            <Button
              label={COPY.household.retry}
              variant="secondary"
              onPress={() => void households.refetch()}
              testID="household-retry"
            />
          </View>
        ) : list === undefined ? null : (
          <>
            {list.length === 0 ? (
              <View style={styles.centered} testID="household-empty">
                <EmptyIcon name="users" />
                <Text style={styles.headline} accessibilityRole="header">
                  {COPY.household.empty.headline}
                </Text>
                <Text style={styles.body}>{COPY.household.empty.body}</Text>
              </View>
            ) : (
              <View style={styles.group}>
                {list.map((household, index) => {
                  const isOpen =
                    active?.kind === 'household' && active.householdId === household.id;
                  const count = household.members.length;
                  return (
                    <Row
                      key={household.id}
                      testID={`household-row-${household.id}`}
                      chevron
                      lastInGroup={index === list.length - 1}
                      onPress={() => router.push(detailHref(household.id))}
                      accessibilityLabel={`${household.name}, ${COPY.household.role[household.role]}${isOpen ? `, ${COPY.household.openNow}` : ''}`}
                    >
                      <RowTitle>{household.name}</RowTitle>
                      <RowSubtitle>
                        {[
                          COPY.household.role[household.role],
                          count === 1
                            ? COPY.household.memberCountOne
                            : COPY.household.memberCountMany.replace('{count}', String(count)),
                          isOpen ? COPY.household.openNow : null,
                        ]
                          .filter((part): part is string => part !== null)
                          .join(' · ')}
                      </RowSubtitle>
                    </Row>
                  );
                })}
              </View>
            )}
            <View style={styles.actions}>
              <Button
                label={COPY.household.create}
                onPress={() => {
                  setCreateError(undefined);
                  setCreateOpen(true);
                }}
                fullWidth
                testID="household-create"
              />
              <Button
                label={COPY.household.join}
                variant="secondary"
                onPress={() => {
                  setJoinError(undefined);
                  setJoinOpen(true);
                }}
                fullWidth
                testID="household-join"
              />
            </View>
          </>
        )}
      </ScrollView>

      <NameSheet
        visible={createOpen}
        mode="create"
        initial=""
        error={createError}
        onClose={() => setCreateOpen(false)}
        onSubmit={create}
      />
      <JoinSheet
        visible={joinOpen}
        error={joinError}
        onClose={() => setJoinOpen(false)}
        onJoin={join}
      />
    </View>
  );
}

const useStyles = createStyles((color) =>
  StyleSheet.create({
    screen: { flex: 1, backgroundColor: color.bg.canvas },
    content: { paddingTop: space[3], paddingBottom: space[8] },
    centered: { padding: space[6], gap: space[3], alignItems: 'center' },
    headline: { ...type.title1, color: color.text.primary, textAlign: 'center' },
    body: { ...type.body, color: color.text.secondary, textAlign: 'center' },
    group: {
      marginHorizontal: space[4],
      borderRadius: radius.lg,
      overflow: 'hidden',
      backgroundColor: color.bg.surface,
      borderWidth: StyleSheet.hairlineWidth,
      borderColor: color.border.hairline,
    },
    actions: { alignSelf: 'stretch', gap: space[3], padding: space[4] },
  }),
);
